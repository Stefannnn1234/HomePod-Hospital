    func testParseNAND() throws {
        let nand = try DiagParsers.parseNAND(Self.framed(Self.nandJSON))
        XCTAssertTrue(nand.ok)
        XCTAssertEqual(nand.source, "ASPStorage")
        XCTAssertEqual(nand.nandStatus, "Ready")
        XCTAssertEqual(nand.vendor, "Toshiba")
        XCTAssertEqual(nand.nandMarketingName, "15nm64Gb0C")
        XCTAssertEqual(nand.chipId, "50504E010508")
        XCTAssertEqual(nand.encryptionType, "AES-CBC")
        XCTAssertEqual(nand.capacityBytes, 16_000_000_000)
        XCTAssertEqual(nand.blocksTotal, 2160)
        XCTAssertEqual(nand.packageBlocksAtEOL, 4051)
        XCTAssertEqual(nand.pagesPerBlockMlc, 256)
        XCTAssertEqual(nand.pageBytes, 16384)
        XCTAssertEqual(nand.disks.map(\.bsd), ["disk0", "disk2", "disk4", "disk3"])
        XCTAssertEqual(nand.mainDisk, "disk0")
        XCTAssertEqual(nand.ioErrors, 0)
        XCTAssertEqual(nand.ioRetries, 0)
        XCTAssertEqual(nand.writeLocked, true)
        XCTAssertEqual(nand.verdict, .pass)
        XCTAssertNotNil(nand.raw)

        let rows = Dictionary(uniqueKeysWithValues: nand.rows.map { ($0.id, $0) })
        XCTAssertEqual(rows["nand.status.controller"]?.value, "Ready")
        XCTAssertEqual(rows["nand.status.controller"]?.verdict, .pass)
        XCTAssertEqual(rows["nand.chip"]?.value, "Toshiba 15nm64Gb0C")
