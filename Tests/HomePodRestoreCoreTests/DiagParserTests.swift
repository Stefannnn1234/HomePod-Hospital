    /// Pod-side shell that answers each `hpdiag-*` invocation with canned output.
    struct FakeShell: RamdiskShell {
        var outputs: [String: String]
        var failing: Set<String> = []

        func run(_ command: String) async throws -> String {
            for (script, output) in outputs.sorted(by: { $0.key.count > $1.key.count }) where command.contains(script) {
                if failing.contains(script) { throw SysCfgError.transportUnavailable("SSH to the ramdisk timed out after 30s.") }
                return output
            }
            return DiagParserTests.framed("sh: \(command): not found", exit: 127)
        }

        func dumpBinary(_ command: String) async throws -> Data { Data() }
    }

    final class Collector<T>: @unchecked Sendable {
        private let lock = NSLock()
        private var items: [T] = []
        func add(_ item: T) { lock.lock(); items.append(item); lock.unlock() }
        var all: [T] { lock.lock(); defer { lock.unlock() }; return items }
    }

    /// Minimal SysCfg blob: reversed signature + reversed tags, NUL-terminated values.
    static func sysCfgBlob(serial: String, wifi: [UInt8], bt: [UInt8]) -> Data {
        var d = Data("gfCS".utf8)
        d.append(contentsOf: [0, 0, 0, 0])
        d.append(Data("mNrS".utf8)); d.append(Data(serial.utf8)); d.append(0)
        d.append(Data("caMW".utf8)); d.append(contentsOf: wifi); d.append(0)
        d.append(Data("caMB".utf8)); d.append(contentsOf: bt); d.append(0)
        return d
    }

    static func allOutputs() -> [String: String] {
        Dictionary(uniqueKeysWithValues: DiagTool.allCases.map { (DiagCommands.script(for: $0), framed(json(for: $0))) })
    }

    func testControllerAssemblesReport() async throws {
        let blob = Self.sysCfgBlob(serial: "CC4VKKTQHQK8", wifi: [0xd0, 0x81, 0x7a, 0xe3, 0x76, 0x94], bt: [0xd0, 0x81, 0x7a, 0xe3, 0x76, 0x95])
        var outputs = Self.allOutputs()
        // Radio script that didn't compare: the Mac side fills it in from SysCfg.
        outputs[DiagCommands.radio] = Self.framed(
            #"{"tool":"radio","ok":true,"wifi":{"present":true,"mac":"d0:81:7a:e3:76:94"},"bt":{"present":true,"mac":"d0:81:7a:e3:76:99"},"verdict":"pass"}"#)
        // Factory script without a serial: falls back to the SysCfg read.
        outputs[DiagCommands.factory] = Self.framed(#"{"tool":"factory","ok":true,"sysCfgSig":"gfCS","tagsPresent":["SrNm","WMac","BMac"],"tagsMissing":[],"verdict":"pass"}"#)
        let pod = BootedPod(transport: FakeSysCfgTransport(seed: blob), shell: FakeShell(outputs: outputs), teardown: {})

        let progress = Collector<FullDiagnosticsController.Progress>()
        let outcome = await FullDiagnosticsController.run(on: pod, onProgress: { progress.add($0) })
        guard case .ok(let report) = outcome else { return XCTFail("expected a report, got \(outcome)") }

        XCTAssertEqual(report.serial, "CC4VKKTQHQK8")
        XCTAssertEqual(report.results.count, 8, "mic + accel fold into one sensors entry")
        XCTAssertTrue(report.incomplete.isEmpty)
        guard case .radio(let radio)? = report.results.first(where: { $0.name == "radio" }) else { return XCTFail("no radio") }
        XCTAssertEqual(radio.wifi?.matchesSysCfg, true)
        XCTAssertEqual(radio.bt?.matchesSysCfg, false)
        XCTAssertEqual(report.overall, .warn)

        let events = progress.all
        XCTAssertEqual(events.count, DiagTool.allCases.count * 2)
        XCTAssertEqual(events.first, .init(tool: .nand, index: 0, total: 9, state: .running))
        XCTAssertEqual(events.last?.fraction, 1)
    }

