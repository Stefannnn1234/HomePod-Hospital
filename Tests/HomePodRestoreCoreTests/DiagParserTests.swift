        XCTAssertEqual(rows["nand.capacity"]?.note, "2160 blocks")
        XCTAssertEqual(rows["nand.ioErrors"]?.value, "read 0, write 0")
        XCTAssertEqual(rows["nand.ioErrors"]?.verdict, .pass)
        XCTAssertEqual(rows["nand.ioRetries"]?.verdict, .pass)
        XCTAssertEqual(rows["nand.eolBlocks"]?.value, "4051")
