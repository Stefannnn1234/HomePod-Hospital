    func testNANDIgnoresFictionalWearCounters() throws {
        // Keys from the pre-capture model. The A8 ASP publishes none of them,
        // so they must not produce rows or move the verdict.
        let nand = try DiagParsers.parseNAND(
            #"{"tool":"nand","ok":true,"nandStatus":"Ready","badBlocks":12,"uncorrectableErrors":4,"wearPercentEstimate":95,"spareBlocksFree":0,"verdict":"pass"}"#)
        XCTAssertEqual(nand.verdict, .pass)
        XCTAssertFalse(nand.rows.contains { $0.id == "nand.wear" || $0.id == "nand.badBlocks" || $0.id == "nand.uncorrectable" || $0.id == "nand.spareBlocks" })
    }

    func testToolThatCouldNotRunIsInformational() throws {
