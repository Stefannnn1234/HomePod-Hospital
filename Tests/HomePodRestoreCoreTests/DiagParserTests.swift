    func testNANDPanicLogRegionErrorsAreNotCountedAgainstTheChip() throws {
        // disk4 (PanicLog on this pod) has 4 read errors; the main NAND has none.
        let nand = try DiagParsers.parseNAND(Self.nandJSON)
        XCTAssertEqual(nand.otherDisksWithErrors.map(\.bsd), ["disk4"])
        XCTAssertEqual(nand.verdict, .pass)
        let row = nand.rows.first { $0.id == "nand.otherRegionErrors" }
        XCTAssertEqual(row?.value, "disk4 (Apple PanicLog Media): 4")
        XCTAssertEqual(row?.verdict, .info)
    }

    func testNANDVerdictIsEscalatedByTheNumbers() throws {
        // The script says pass, but the main NAND disk has I/O errors.
        let failing = try DiagParsers.parseNAND(
            #"{"tool":"nand","ok":true,"nandStatus":"Ready","ioErrorsRead":3,"ioErrorsWrite":1,"verdict":"pass"}"#)
        XCTAssertEqual(failing.ioErrors, 4)
        XCTAssertEqual(failing.verdict, .fail)
        // A controller that isn't Ready is a failure whatever the script said.
        let notReady = try DiagParsers.parseNAND(#"{"tool":"nand","nandStatus":"Not Ready","verdict":"pass"}"#)
        XCTAssertEqual(notReady.verdict, .fail)
        XCTAssertEqual(notReady.rows.first { $0.id == "nand.status.controller" }?.verdict, .fail)
        // Retries alone are a warning.
        let retrying = try DiagParsers.parseNAND(#"{"tool":"nand","nandStatus":"Ready","ioRetriesRead":2,"ioErrorsRead":0}"#)
        XCTAssertEqual(retrying.verdict, .warn)
    }

    func testNANDMainDiskIsFoundByMediaNameNotNumber() throws {
        // No top-level figures and the NAND is disk1 here: the per-disk entry
        // named "Apple NAND Media" supplies them.
