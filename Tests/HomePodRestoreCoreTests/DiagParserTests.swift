    // MARK: Sentinel extraction

    func testExtractsJSONBetweenSentinels() throws {
        let data = try DiagParsers.extractJSON(from: Self.framed(#"{"tool":"nand","ok":true}"#))
        XCTAssertEqual(String(decoding: data, as: UTF8.self), #"{"tool":"nand","ok":true}"#)
    }

    func testNestedSentinelsResolveToInnermostPair() throws {
        // Wrapper frames the script, and the script frames itself.
        let inner = "\(DiagCommands.beginMarker)\n{\"tool\":\"nand\"}\n\(DiagCommands.endMarker)"
        let data = try DiagParsers.extractJSON(from: Self.framed(inner))
        XCTAssertEqual(String(decoding: data, as: UTF8.self), #"{"tool":"nand"}"#)
    }

    func testStderrNoiseInsideTheFrameIsDropped() throws {
        let body = "ioreg: warning {not json}\n{\"tool\":\"nand\",\"blocksTotal\":3}\ntrailing noise"
        let nand = try DiagParsers.parseNAND(Self.framed(body))
        XCTAssertEqual(nand.blocksTotal, 3)
    }

    func testAnsiColourIsStripped() throws {
        let body = "\u{1B}[32m{\"tool\":\"nand\",\"blocksTotal\":7}\u{1B}[0m"
        XCTAssertEqual(try DiagParsers.parseNAND(Self.framed(body)).blocksTotal, 7)
    }

    func testFallsBackWithoutSentinels() throws {
        XCTAssertEqual(try DiagParsers.parseNAND("banner\n{\"tool\":\"nand\",\"blocksTotal\":1}\n").blocksTotal, 1)
    }

    func testTruncatedOutputWithoutEndMarker() throws {
        let text = "\(DiagCommands.beginMarker)\n{\"tool\":\"nand\",\"blocksTotal\":2}\n"
        XCTAssertEqual(try DiagParsers.parseNAND(text).blocksTotal, 2)
    }

    func testMissingScriptIsReportedAsToolMissing() {
        let text = Self.framed("sh: hpdiag-nand: not found", exit: 127)
        XCTAssertThrowsError(try DiagParsers.parseNAND(text)) { XCTAssertEqual($0 as? DiagParseError, .toolMissing) }
    }

    func testEmptyFrameReportsExitStatus() {
        let text = "\(DiagCommands.beginMarker)\n\n\(DiagCommands.endMarker)\n\(DiagCommands.exitMarkerPrefix)2===\n"
        XCTAssertEqual(DiagParsers.exitStatus(from: text), 2)
        XCTAssertThrowsError(try DiagParsers.parseNAND(text)) {
            XCTAssertEqual($0 as? DiagParseError, .noPayload(exitStatus: 2))
        }
    }

    func testGarbageJSONIsInvalidJSON() {
        XCTAssertThrowsError(try DiagParsers.parseNAND(Self.framed("{\"tool\": nand,,}"))) {
            guard case .invalidJSON? = $0 as? DiagParseError else { return XCTFail("expected invalidJSON, got \($0)") }
        }
    }

    func testInvocationFramesAndSetsPath() {
        let line = DiagCommands.invocation(for: .nand)
        XCTAssertTrue(line.contains("/usr/local/bin"))
        XCTAssertTrue(line.contains("hpdiag-nand"))
        XCTAssertTrue(line.contains(DiagCommands.beginMarker))
