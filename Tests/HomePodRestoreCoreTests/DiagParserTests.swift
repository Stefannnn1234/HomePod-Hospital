    func testRadioCrossCheckAgainstSysCfg() throws {
        let radio = try DiagParsers.parseRadio(
            #"{"tool":"radio","wifi":{"present":true,"mac":"D0:81:7A:E3:76:94"},"bt":{"present":true,"mac":"d0:81:7a:e3:76:95"},"verdict":"pass"}"#)
        XCTAssertNil(radio.wifi?.matchesSysCfg)

        let same = radio.crossChecked(wifiMAC: "d0:81:7a:e3:76:94", bluetoothMAC: "d0:81:7a:e3:76:95")
        XCTAssertEqual(same.wifi?.matchesSysCfg, true)
        XCTAssertEqual(same.verdict, .pass)

        let different = radio.crossChecked(wifiMAC: "d0:81:7a:00:00:01", bluetoothMAC: nil)
        XCTAssertEqual(different.wifi?.matchesSysCfg, false)
        XCTAssertNil(different.bt?.matchesSysCfg)
        XCTAssertEqual(different.verdict, .warn)

        // A truncated SysCfg MAC (parser stops at a NUL byte) must not be compared.
        let truncated = radio.crossChecked(wifiMAC: "d0:81:7a", bluetoothMAC: nil)
        XCTAssertNil(truncated.wifi?.matchesSysCfg)
        XCTAssertEqual(truncated.verdict, .pass)
    }

